// Bundles the migrations and the sample seed into one TS module, so demo mode
// (no DATABASE_URL) can boot an in-memory Postgres anywhere, including Vercel.
//
//   pnpm --filter @forkd/db demo:build
//
// To refresh demo/seed.sql after changing seed.ts, seed a real database and run:
//   pg_dump "$DATABASE_URL" --data-only --inserts --column-inserts -t cities -t categories -t '"user"' \
//     -t profiles -t spots -t spot_categories -t visits -t spot_stats | grep '^INSERT' > demo/seed.sql
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("drizzle/meta/_journal.json", root), "utf8"));
const migrations = journal.entries.flatMap((e) =>
  readFileSync(new URL(`drizzle/${e.tag}.sql`, root), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
);

// Insert parents before children so foreign keys hold.
const ORDER = ["cities", "categories", '"user"', "profiles", "spots", "spot_categories", "visits", "spot_stats"];
const lines = readFileSync(new URL("demo/seed.sql", root), "utf8").split("\n").filter((l) => l.startsWith("INSERT"));
const table = (l) => l.match(/^INSERT INTO (?:public\.)?("?\w+"?)/)?.[1] ?? "";
lines.sort((a, b) => ORDER.indexOf(table(a)) - ORDER.indexOf(table(b)));

const out = `// Generated by scripts/build-demo.mjs. Do not edit by hand.
export const DEMO_MIGRATIONS: string[] = ${JSON.stringify(migrations)};
export const DEMO_SEED: string = ${JSON.stringify(lines.join("\n"))};
`;
writeFileSync(new URL("src/demo-sql.generated.ts", root), out);
console.log(`Bundled ${migrations.length} migration statements and ${lines.length} seed rows.`);
